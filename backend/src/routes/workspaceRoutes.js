const express = require("express");
const authenticateToken = require("../middleware/authenticateToken");
const requireWorkspaceMember = require("../middleware/requireWorkspaceMember");
const c = require("../controllers/workspaceController");
const teams = require("../controllers/teamController");
const analytics = require("../controllers/analyticsController");
const validateIds = require("../middleware/validateIds");
const wrap = (fn) => (req, res, next) => Promise.resolve(fn(req, res)).catch(next);

const router = express.Router();
router.use(authenticateToken);
router.get("/", wrap(c.listWorkspaces));
router.post("/", wrap(c.createWorkspace));
router.post("/invitations/accept", wrap(c.acceptInvitation));
router.get("/:workspaceId", validateIds(["workspaceId"]), requireWorkspaceMember(), wrap(c.getWorkspace));
router.patch("/:workspaceId", validateIds(["workspaceId"]), requireWorkspaceMember({ role: "admin" }), wrap(c.updateWorkspace));
router.delete("/:workspaceId", validateIds(["workspaceId"]), requireWorkspaceMember({ role: "owner" }), wrap(c.deleteWorkspace));
router.get("/:workspaceId/members", validateIds(["workspaceId"]), requireWorkspaceMember(), wrap(c.listMembers));
router.post("/:workspaceId/invitations", validateIds(["workspaceId"]), requireWorkspaceMember({ role: "admin" }), wrap(c.inviteMember));
router.get("/:workspaceId/teams", validateIds(["workspaceId"]), requireWorkspaceMember(), wrap(teams.listTeams));
router.post("/:workspaceId/teams", validateIds(["workspaceId"]), requireWorkspaceMember({ role: "manager" }), wrap(teams.createTeam));
router.get("/:workspaceId/teams/:teamId", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember(), wrap(teams.getTeam));
router.patch("/:workspaceId/teams/:teamId", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember({ role: "manager" }), wrap(teams.updateTeam));
router.delete("/:workspaceId/teams/:teamId", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember({ role: "manager" }), wrap(teams.deleteTeam));
router.get("/:workspaceId/teams/:teamId/members", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember(), wrap(teams.listTeamMembers));
router.get("/:workspaceId/teams/:teamId/productivity", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember(), wrap(analytics.getTeamProductivity));
router.post("/:workspaceId/teams/:teamId/members", validateIds(["workspaceId", "teamId"]), requireWorkspaceMember({ role: "manager" }), wrap(teams.addTeamMember));
router.delete("/:workspaceId/teams/:teamId/members/:userId", validateIds(["workspaceId", "teamId", "userId"]), requireWorkspaceMember({ role: "manager" }), wrap(teams.removeTeamMember));

module.exports = router;
